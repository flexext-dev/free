declare(strict_types=1);

namespace Visacom\Plugin\System\FlexextAiSeoFree;

defined('_JEXEC') or die;

use Joomla\Registry\Registry;

/**
 * AI Bot Directives Manager & Robots.txt Recommender.
 */
final class BotShieldManager
{
    public static function output(Registry $params): void
    {
        header('Content-Type: text/plain; charset=utf-8');
        echo "# AI Crawler Directives (Generated by FlexExt AI SEO Readiness)\n";
        echo "# You can copy and paste these rules into your site robots.txt file:\n\n";

        $bots = [
            'GPTBot'          => $params->get('gptbot_action', 'allow'),
            'ClaudeBot'        => $params->get('claudebot_action', 'allow'),
            'PerplexityBot'    => $params->get('perplexity_action', 'allow'),
            'CCBot'            => $params->get('ccbot_action', 'disallow'),
        ];

        foreach ($bots as $bot => $action) {
            echo "User-agent: " . $bot . "\n";
            if ($action === 'disallow') {
                echo "Disallow: /\n\n";
            } else {
                echo "Allow: /\n\n";
            }
        }
    }
}
