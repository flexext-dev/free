declare(strict_types=1);

namespace Visacom\Plugin\System\FlexextAiSeoFree;

defined('_JEXEC') or die;

use Joomla\CMS\Factory;
use Joomla\CMS\Uri\Uri;
use Joomla\Registry\Registry;

/**
 * Standard /llms.txt Generator conforming to the https://llmstxt.org specification.
 */
final class LlmsTxtGenerator
{
    public static function output(Registry $params): void
    {
        $app = Factory::getApplication();
        $siteName = $params->get('site_name') ?: $app->get('sitename', 'Website');
        $siteSummary = $params->get('site_summary', 'Official website with comprehensive information and services.');
        $contactUrl = $params->get('contact_url', '/contact');
        $rootUrl = rtrim(Uri::root(), '/');

        header('Content-Type: text/markdown; charset=utf-8');
        header('Cache-Control: public, max-age=3600');

        echo "# " . $siteName . "\n\n";
        echo "> " . $siteSummary . "\n\n";
        echo "## Key Information & Links\n\n";
        echo "- [Homepage](" . $rootUrl . "/): Main starting point and overview.\n";
        echo "- [Contact](" . $rootUrl . $contactUrl . "): Official contact details, inquiries, and customer support.\n\n";
        echo "## AI & Agent Policy\n\n";
        echo "This website publishes structured content for AI agents and LLMs. Crawlers must respect standard robots.txt directives.\n";
        echo "Generated by FlexExt AI SEO & Agent Readiness (https://flexext.dev).\n";
    }
}
